def prepare_project(project, app_name="App", design=None):
    design = DESIGN_DEFAULT if design is None else design
    project = Path(project)
    (project / "pages").mkdir(parents=True, exist_ok=True)
    if not (project / "kit").exists():
        shutil.copytree(KIT_NEXT if design else KIT, project / "kit", ignore=shutil.ignore_patterns("__pycache__"))
    (project / "pages" / "__init__.py").touch()
    (project / "app.py").write_text(APP_PY.format(name=app_name))


def extract_code(text, must_define=None):
    """The code block from a reply. With must_define, prefer the block that defines that function
    (small models sometimes echo the guide back in an extra block)."""
    blocks = re.findall(r"```[a-zA-Z0-9]*[ \t]*\n(.*?)```", text, re.S)
    if not blocks:
        return None
    if must_define:
        good = [b for b in blocks if f"def {must_define}(" in b]
        blocks = good or blocks
    return blocks[0].rstrip() + "\n"


def repair_syntax(code, rounds=6):
    """Mechanical repair of the commonest small-model slip: a missing comma between arguments that
    sit on separate lines. Only applied when Python itself says a comma is probably missing, and a
    candidate repair is kept only if it makes the error go away or move further down.
    Returns (code, list of repairs)."""
    repairs = []

    def err(c):
        try:
            compile(c, "x", "exec")
            return None
        except SyntaxError as e:
            return e

    for _ in range(rounds):
        e = err(code)
        if e is None or "forgot a comma" not in (e.msg or ""):
            return code, repairs
        lines = code.splitlines()
        fixed = False
        for i in range(max(0, (e.lineno or 1) - 2), min(len(lines), (e.end_lineno or e.lineno or 1))):
            if not lines[i].strip() or lines[i].rstrip().endswith((",", "(", "[", "{")):
                continue
            trial = lines[:i] + [lines[i].rstrip() + ","] + lines[i + 1:]
            t = "\n".join(trial) + "\n"
            e2 = err(t)
            if e2 is None or (e2.lineno or 0) > (e.lineno or 0):
                code, fixed = t, True
                repairs.append(f"added a missing comma at the end of line {i + 1}")
                break
        if not fixed:
            return code, repairs
    return code, repairs


def extract_files(text):
    """'FILE: path' + code block pairs -> {path: code}"""
    out = {}
    for m in re.finditer(r"FILE:\s*[`'\"]?([\w./-]+)[`'\"]?\s*\n+```[a-zA-Z0-9]*[ \t]*\n(.*?)```", text, re.S):
        path = m.group(1).lstrip("./")
        if path.endswith(".py") and ".." not in path and not path.startswith(("kit/", "/")) and path != "app.py":
            out[path] = m.group(2).rstrip() + "\n"
    return out


class Meter:
    """Counts model use for the report."""

    def __init__(self):
        self.calls, self.seconds, self.tokens = 0, 0.0, 0

    def chat(self, client, messages, **kw):
        reply = client.chat(messages, **kw)
        self.calls += 1
        self.seconds += reply.seconds
        self.tokens += reply.completion_tokens
        return reply


class TrialRun:
    """Runs a candidate version of the project in the sandbox, in a scratch copy with an empty database."""

    def __init__(self, project, sandbox, scratch, files=None):
        self.sandbox, self.dir = sandbox, Path(scratch)
        shutil.rmtree(self.dir, ignore_errors=True)
        shutil.copytree(project, self.dir, ignore=COPY_IGNORE)
        for rel, code in (files or {}).items():
            (self.dir / rel).parent.mkdir(parents=True, exist_ok=True)
            (self.dir / rel).write_text(code)
        self.server, self.log = None, ""

    def start(self):
        self.stop()
        self.server = self.sandbox.start(["python3", "app.py"], self.dir)
        if self.server.wait_ready("/static/neuron.css"):
            return self.server.url
        self.stop()
        return None

    def stop(self):
        if self.server:
            self.log += self.server.stop()
            self.server = None

    def run_checks(self, checks):
        """Returns (passed, failure text)."""
        try:
            for check in checks:
                self.stop()
                for old in self.dir.glob("data.db*"):       # every check starts from an empty database
                    old.unlink()
                url = self.start()
                if not url:
                    return False, "The app did not start:\n" + self.log[-1500:]
                ok, why = CheckRunner(url, restart=self.start).run(check)
                if not ok:
                    self.stop()
                    errors = "\n".join(l for l in self.log.splitlines()[-25:])
                    return False, f"Check '{check['name']}' failed: {why}" + (f"\nApp error output:\n{errors}" if "Traceback" in errors else "")
        finally:
            self.stop()
        return True, ""


def plan(request, client, meter, content_rules=False):
    """Planner role: request -> validated spec (up to two repair rounds). Returns (spec, problems).
    content_rules: a site's words are checked (neuron.design.content): invented facts, leftover template text,
    filler, repetition and duplicated sections go back to the planner with plain instructions; invented facts that
    survive every round are removed and recorded in spec["content_notes"]."""
    from ..design import content
    messages = [{"role": "system", "content": prompts.PLANNER_SYSTEM},
                {"role": "user", "content": "Request: " + prompts.PLANNER_EXAMPLE_REQUEST},
                {"role": "assistant", "content": json.dumps(prompts.PLANNER_EXAMPLE_SPEC)},
                {"role": "user", "content": "Request: " + prompts.PLANNER_SITE_REQUEST},
                {"role": "assistant", "content": json.dumps(prompts.PLANNER_SITE_SPEC)},
                {"role": "user", "content": "Request: " + prompts.PLANNER_RULE_REQUEST},
                {"role": "assistant", "content": json.dumps(prompts.PLANNER_RULE_SPEC)},
                {"role": "user", "content": "Request: " + request}]
    problems = ["no reply"]
    for rnd in range(3):    # first try + two repair rounds
        reply = meter.chat(client, messages, max_tokens=1500, temperature=0.1, json_schema=PLAN_SCHEMA)
        try:
            raw = json.loads(reply.text[reply.text.index("{"): reply.text.rindex("}") + 1])
        except ValueError:
            raw, problems = None, ["the reply was not valid JSON"]
        if raw is not None:
            spec, problems = normalise(raw)
            if not problems and content_rules and spec["kind"] == "site":
                issues = content.check(content.spec_pieces(spec), request)
                if issues and rnd < 2:
                    messages += [{"role": "assistant", "content": reply.text},
                                 {"role": "user", "content": "The words of that page have problems:\n" + content.feedback(issues)
                                  + "\nSend the corrected specification."}]
                    continue
                notes = [f"{i['kind']}: {i['where']}: {i['detail']}" for i in issues]
                removed = content.remove_invented(spec, request) if any(i["kind"] == "invented" for i in issues) else []
                spec["content_notes"] = [f"removed {r}" for r in removed] + \
                    [n for n in notes if not n.startswith("invented")]
                return spec, []
            if not problems:
                return spec, []
        messages += [{"role": "assistant", "content": reply.text},
                     {"role": "user", "content": "That specification cannot be used: " + "; ".join(problems) + ". Send a corrected one."}]
    return None, problems


def _builder_prompt(state, task):
    s = state.slice_for(task)
    # on a retry the guide is left out: small models tend to copy it back instead of writing the file
    parts = ([] if s.get("last_failure") else [prompts.KIT_GUIDE, ""]) + \
        ["# Example of a similar file", "```python", prompts.EXAMPLES[task["example"]].rstrip(), "```"]
    if s["interfaces"]:
        parts += ["", "# Files that already exist in this project", s["interfaces"]]
    parts += ["", f"# Your task: {task['file']}", s["contract"]]
    if s.get("last_failure"):
        parts += ["", "# Your previous version failed", "```python", s["previous_code"].rstrip(), "```", s["last_failure"]]
        if s.get("advice"):
            parts += ["Reviewer's advice: " + s["advice"]]
        parts += ["Write a corrected complete file."]
    return "\n".join(parts)


def build_full(project, request, runner, sandbox, log=print, max_seconds=None, design=None, shots_dir=None, templates_allowed=None,
               photos=()):
    """Build (or resume building) a project. Returns a summary dict.
    templates_allowed: after the model fails a task MAX_ATTEMPTS times, try the fixed template for that file
    (on by default; off reproduces the step-3 evaluations). Every file says who made it."""
    design = DESIGN_DEFAULT if design is None else design
    templates_allowed = (os.environ.get("NEURON_TEMPLATES", "1") != "0") if templates_allowed is None else templates_allowed
    project, state, meter, t0 = Path(project), ProjectState(project), Meter(), time.time()
    out_of_time = lambda: max_seconds is not None and time.time() - t0 > max_seconds
    if state.exists():
        interrupted = state.resume()
        log(f"resuming: {sum(t['status'] == 'done' for t in state.tasks())} tasks already done, interrupted: {interrupted}")
    else:
        spec, problems = plan(request, runner.client("planner"), meter, content_rules=bool(design))
        if spec is None:
            return {"ok": False, "stage": "plan", "error": "; ".join(problems), "llm": vars(meter), "resumed": False}
        if design and spec["kind"] == "site":            # pictures: the owner's first, labelled placeholders for the rest
            from ..media import images
            from . import design_step, site_images
            prepare_project(project, spec["app_name"], design)
            look = design_step.choose_and_save(project, request, spec)
            r = look["palette"]["roles"]
            m = images.prepare(project, site_images.slots(request, spec), (r["dominant"], r["support"], r["accent"]), owner_photos=photos)
            spec["images"] = [{"slot": x["slot"], "file": x["file"], "alt": x["purpose"]} for x in m.slots]
            log(f"pictures: {m.summary()}")
        tasks, acceptance, purposes = expand(spec)
        spec["not_built"] = unsupported_features(request, spec) + relations.dropped_gaps(request, spec)
        if spec["not_built"]:
            log(f"cannot build yet (will be reported): {spec['not_built']}")
        prepare_project(project, spec["app_name"], design)
        state.create(request, "build", spec, tasks, acceptance, purposes)
        if design:
            from . import design_step
            look = design_step.choose_and_save(project, request, spec, state)
            log(f"design: {look['mood']} / {look['palette']['name']} / hero {look['variants']['hero']}")
        for d in spec.get("dropped", []):
            state.decide("plan", "dropped", d)
        for n in spec.get("content_notes", []):
            state.decide("plan", "content", n)
        state.decide("plan", "spec", f"planned a {spec['kind']} called {spec['app_name']} with tasks: "
                     + ", ".join(t["id"] for t in tasks))
        log(f"planned {len(tasks)} tasks: {[t['id'] for t in tasks]}")
    state.journal("session", models={r: runner.model_for(r) for r in ("planner", "reviewer", "builder")})
    acceptance = state.acceptance()
    scratch = project.parent / (project.name + "__trial")
    while not out_of_time():
        task = state.next_task()
        if task is None:
            break
        state.update_task(task["id"], status="in_progress")
        checks = [c for c in acceptance if c["task"] == task["id"]]
        passed = False
        if task.get("deterministic") and templates_allowed and not task["attempts"]:      # off in step-3 reproduction
            code = templates.file_for(state.spec()["spec"], task)
            ok, why = TrialRun(project, sandbox, scratch, {task["file"]: code}).run_checks(checks)
            state.record_test(task["id"], 1, ok, "written by plain code: passed" if ok else why.splitlines()[0], why)
            state.add_attempt(task["id"], {"n": 1, "passed": ok, "made_by": "code", **({} if ok else {"failure": why})})
            task = state.task(task["id"])
            if ok:
                (project / task["file"]).parent.mkdir(parents=True, exist_ok=True)
                (project / task["file"]).write_text(code)
                state.update_task(task["id"], status="done", made_by="code")
                state.refresh_map()
                log(f"  task {task['id']}: written by plain code, checks passed")
                continue
        while len(task["attempts"]) < MAX_ATTEMPTS and not passed and not out_of_time():
            n = len(task["attempts"]) + 1
            attempt = {"n": n, "passed": False}
            reply = meter.chat(runner.client("builder"), [{"role": "system", "content": prompts.BUILDER_SYSTEM},
                                                          {"role": "user", "content": _builder_prompt(state, task)}],
                               max_tokens=1400, temperature=0.1 if n == 1 else 0.5)
            code = extract_code(reply.text, task["must_define"])
            failure = None
            if code is None:
                failure = "The reply had no complete ```python block."
            elif f"def {task['must_define']}(" not in code and "kit.web" in code and "app.db.execute(sql" in code:
                failure, code = "The reply repeated the kit guide instead of writing the file.", None
            else:
                code, repairs = repair_syntax(code)
                if repairs:
                    attempt["repairs"] = repairs
                    state.decide(task["id"], "repair", "; ".join(repairs))
                attempt["code"] = code
                try:
                    compile(code, task["file"], "exec")
                    if f"def {task['must_define']}(" not in code:
                        failure = f"The file does not define {task['must_define']}(app)."
                except SyntaxError as e:
                    failure = f"The file is not valid Python: {e.msg} (line {e.lineno})."
            if failure is None:
                ok, failure = TrialRun(project, sandbox, scratch, {task["file"]: code}).run_checks(checks)
                state.record_test(task["id"], n, ok, "passed" if ok else failure.splitlines()[0], failure)
                if ok and task.get("review") and not any(a.get("review_used") for a in task["attempts"]):
                    verdict = _content_review(state, code, runner.client("reviewer"), meter)
                    attempt["review_used"] = True
                    if verdict:
                        ok, failure = False, "A reviewer compared the page with the request. Missing: " + "; ".join(verdict)
                        state.decide(task["id"], "review", failure)
                passed = ok
            if passed:
                (project / task["file"]).parent.mkdir(parents=True, exist_ok=True)
                (project / task["file"]).write_text(code)
                attempt["passed"] = True
            else:
                attempt["failure"] = failure
                if code is not None and len(task["attempts"]) + 1 < MAX_ATTEMPTS:
                    try:
                        advice = meter.chat(runner.client("reviewer"), [
                            {"role": "system", "content": prompts.REVIEWER_SYSTEM},
                            {"role": "user", "content": f"Contract:\n{task['contract']}\n\nThe file:\n```python\n{code}```\n\nWhat happened:\n{failure[-1500:]}"}],
                            max_tokens=200, temperature=0.2).text.strip()
                    except LLMUnavailable:
                        advice = ""
                    attempt["advice"] = advice
                    state.decide(task["id"], "diagnosis", advice)
            state.add_attempt(task["id"], attempt)
            task = state.task(task["id"])
            log(f"  task {task['id']} attempt {n}: {'passed' if passed else 'failed - ' + (failure or '').splitlines()[0][:120]}")
        if not passed and out_of_time() and len(task["attempts"]) < MAX_ATTEMPTS:
            state.update_task(task["id"], status="pending")
            break
        made_by = "model" if passed else None
        if not passed and templates_allowed and not out_of_time():
            code = templates.file_for(state.spec()["spec"], task)
            if code is not None:
                ok, why = TrialRun(project, sandbox, scratch, {task["file"]: code}).run_checks(checks)
                state.record_test(task["id"], len(task["attempts"]) + 1, ok, "template passed" if ok else why.splitlines()[0], why)
                state.decide(task["id"], "template", f"the model failed {len(task['attempts'])} times; the fixed template "
                             + ("passed the same checks and was used" if ok else "also failed: " + why.splitlines()[0]))
                if ok:
                    (project / task["file"]).parent.mkdir(parents=True, exist_ok=True)
                    (project / task["file"]).write_text(code)
                    passed, made_by = True, "template"
                log(f"  task {task['id']} template: {'passed' if ok else 'failed'}")
        state.update_task(task["id"], status="done" if passed else "failed", made_by=made_by)
        state.refresh_map()
    shutil.rmtree(scratch, ignore_errors=True)
    tasks = state.tasks()
    final_ok, final_why = False, "not all tasks are done"
    if all(t["status"] == "done" for t in tasks):
        final_ok, final_why = TrialRun(project, sandbox, scratch).run_checks(acceptance)
        state.record_test("final", 1, final_ok, "all acceptance checks passed" if final_ok else final_why.splitlines()[0], final_why)
        shutil.rmtree(scratch, ignore_errors=True)
    design_result = None
    if final_ok and design and (project / "theme.json").exists():
        from . import design_step
        design_result = design_step.review(project, state.spec()["spec"], sandbox, state, shots_dir=shots_dir, log=log)
    return {"ok": final_ok, "stage": "done" if state.finished() else "out of time", "error": "" if final_ok else final_why,
            "design": design_result["final"] if design_result else None,
            "tasks": {t["id"]: {"status": t["status"], "attempts": len(t["attempts"]), "made_by": t.get("made_by")} for t in tasks},
            "made_by": {k: sum(t.get("made_by") == k for t in tasks) for k in ("model", "template", "code")},
            "not_built": (state.spec()["spec"] or {}).get("not_built", []),
            "content_notes": (state.spec()["spec"] or {}).get("content_notes", []),
            "content_problems": _final_content(state, request) if design else [],
            "llm": vars(meter), "model_loads": runner.loads, "seconds": round(time.time() - t0, 1)}


def _final_content(state, request):
    """The words of the finished site, checked once more (nothing invented, no template text, filler or repeats)."""
    spec = state.spec()["spec"] or {}
    if spec.get("kind") != "site":
        return []
    from ..design import content
    return [f"{i['kind']}: {i['where']}: {i['detail']}" for i in content.check(content.spec_pieces(spec), request)]


def _content_review(state, code, client, meter):
    """Reviewer role: is anything the owner asked for missing from the page? Returns a list (empty = fine)."""
    request = state.spec()["request"]
    schema = {"type": "object", "required": ["ok", "missing"],
              "properties": {"ok": {"type": "boolean"}, "missing": {"type": "array", "maxItems": 5, "items": {"type": "string"}}}}
    try:
        reply = meter.chat(client, [{"role": "system", "content": prompts.CONTENT_REVIEW_SYSTEM},
                                    {"role": "user", "content": f"The owner asked:\n{request}\n\nThe page's code:\n```python\n{code}```"}],
                           max_tokens=200, temperature=0.1, json_schema=schema)
        data = json.loads(reply.text[reply.text.index("{"): reply.text.rindex("}") + 1])
    except (LLMUnavailable, ValueError):
        return []
    missing = [str(m) for m in data.get("missing") or [] if str(m).strip()]
    if data.get("ok") or not missing:
        return []
    # A reviewer's claim is checked, not trusted: an item counts as missing only if most of its
    # words really are absent from the text the page shows (the string literals in the code).
    try:
        shown = " ".join(n.value for n in ast.walk(ast.parse(code)) if isinstance(n, ast.Constant) and isinstance(n.value, str)).lower()
    except SyntaxError:
        return missing[:5]
    really = []
    for item in missing:
        words = [w for w in re.findall(r"[a-z0-9]+", item.lower()) if len(w) > 3 and w not in STOP_WORDS]
        if words and sum(w in shown for w in words) < len(words) / 2:
            really.append(item)
    if len(really) < len(missing):
        state.decide("review", "reviewer_overruled", f"reviewer said missing: {missing}; the page shows most of: "
                     f"{[m for m in missing if m not in really]}")
    return really[:5]


STOP_WORDS = {"with", "that", "this", "about", "each", "they", "their", "page", "short", "line", "show", "shows",
              "have", "from", "your", "what", "where", "when", "should", "would", "will", "must", "also", "make"}


def build_base(project, request, runner, sandbox, log=print, max_seconds=None, design=None, shots_dir=None):
    """Without A and B: one prompt for the whole app, 'does it start?' as the only feedback."""
    design = DESIGN_DEFAULT if design is None else design
    project, meter, t0 = Path(project), Meter(), time.time()
    shutil.rmtree(project, ignore_errors=True)       # nothing is kept between sessions
    prepare_project(project, design=design)
    if design:     # the same kit and design engine as FULL, but no saved state and no design review (those are A and B)
        from ..design import engine
        (project / "theme.json").write_text(json.dumps(engine.choose(request), indent=1))
    examples = "\n".join(f"```python\n{prompts.EXAMPLES[k].rstrip()}\n```" for k in ("schema", "entity", "dashboard", "home"))
    base = f"{prompts.KIT_GUIDE}\n\n# Example files\n{examples}\n\n{prompts.BASE_TASK}{request}"
    messages = [{"role": "system", "content": prompts.BASE_SYSTEM}, {"role": "user", "content": base}]
    scratch = project.parent / (project.name + "__trial")
    rounds, ok, why = [], False, ""
    for n in range(1, MAX_ATTEMPTS + 1):
        if max_seconds is not None and time.time() - t0 > max_seconds:
            why = "out of time"
            break
        reply = meter.chat(runner.client("builder"), messages, max_tokens=3000, temperature=0.1 if n == 1 else 0.5)
        files = extract_files(reply.text)
        if "schema.py" not in files:
            why = "The reply did not contain schema.py as 'FILE: schema.py' followed by a python block."
        else:
            why = ""
            for rel, code in files.items():
                try:
                    compile(code, rel, "exec")
                except SyntaxError as e:
                    why = f"{rel} is not valid Python: {e.msg} (line {e.lineno})."
            if not why:
                ok, why = TrialRun(project, sandbox, scratch, files).run_checks(
                    [{"name": "home page opens", "steps": [{"get": "/", "expect_status": [200]}]}])
        rounds.append({"n": n, "files": sorted(files), "ok": ok, "problem": why.splitlines()[0] if why else ""})
        log(f"  round {n}: {'app starts' if ok else 'failed - ' + rounds[-1]['problem'][:120]}")
        if files and (ok or n == MAX_ATTEMPTS or "schema.py" in files):
            for rel, code in files.items():       # keep the latest version on disk either way
                (project / rel).parent.mkdir(parents=True, exist_ok=True)
                (project / rel).write_text(code)
        if ok:
            break
        messages = messages[:2] + [{"role": "assistant", "content": reply.text[:6000]},
                                   {"role": "user", "content": f"That did not work.\n{why[-1500:]}\nSend all the files again, corrected."}]
    shutil.rmtree(scratch, ignore_errors=True)
    return {"ok": ok, "stage": "done", "error": "" if ok else why, "rounds": rounds, "llm": vars(meter),
            "model_loads": runner.loads, "seconds": round(time.time() - t0, 1)}
