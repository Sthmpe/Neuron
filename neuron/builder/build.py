"""The builder loop for builds (B), on top of the project state (A).

FULL  : plan (planner role) -> spec -> tasks -> for each task: build (builder role) -> run it in the
        sandbox -> acceptance checks -> on failure: review (reviewer role) -> fix -> next task.
        Everything is written to .neuron/ as it happens, so a killed build resumes where it stopped.
BASE  : the same model and kit without A and B: one prompt, whole app at once, no state, no tasks,
        no acceptance checks. It only gets "did the app start?" as feedback, up to 3 rounds.
"""
import json
import re
import shutil
import time
from pathlib import Path

from ..brain.llm import LLMUnavailable
from . import prompts
from .checks import CheckRunner
from .spec import SPEC_SCHEMA, expand, normalise
from .state import ProjectState

KIT = Path(__file__).resolve().parents[1] / "kit"
APP_PY = '''"""Starts the app. Generated by NEURON - do not edit."""
from kit.web import App
import schema

app = App({name!r})
schema.setup(app)
app.load_pages("pages")

if __name__ == "__main__":
    app.run()
'''
MAX_ATTEMPTS = 3
COPY_IGNORE = shutil.ignore_patterns(".neuron", "__pycache__", "*.pyc", "data.db*", "*.db-journal")


def prepare_project(project, app_name="App"):
    project = Path(project)
    (project / "pages").mkdir(parents=True, exist_ok=True)
    if not (project / "kit").exists():
        shutil.copytree(KIT, project / "kit", ignore=shutil.ignore_patterns("__pycache__"))
    (project / "pages" / "__init__.py").touch()
    (project / "app.py").write_text(APP_PY.format(name=app_name))


def extract_code(text):
    blocks = re.findall(r"```[a-zA-Z0-9]*[ \t]*\n(.*?)```", text, re.S)
    return (blocks[0].rstrip() + "\n") if blocks else None


def extract_files(text):
    """'FILE: path' + code block pairs -> {path: code}"""
    out = {}
    for m in re.finditer(r"FILE:\s*[`'\"]?([\w./-]+)[`'\"]?\s*\n+```[a-zA-Z0-9]*[ \t]*\n(.*?)```", text, re.S):
        path = m.group(1).lstrip("./")
        if path.endswith(".py") and ".." not in path and not path.startswith(("kit/", "/")) and path != "app.py":
            out[path] = m.group(2).rstrip() + "\n"
    return out


class Meter:
    """Counts model use for the report."""

    def __init__(self):
        self.calls, self.seconds, self.tokens = 0, 0.0, 0

    def chat(self, client, messages, **kw):
        reply = client.chat(messages, **kw)
        self.calls += 1
        self.seconds += reply.seconds
        self.tokens += reply.completion_tokens
        return reply


class TrialRun:
    """Runs a candidate version of the project in the sandbox, in a scratch copy with an empty database."""

    def __init__(self, project, sandbox, scratch, files=None):
        self.sandbox, self.dir = sandbox, Path(scratch)
        shutil.rmtree(self.dir, ignore_errors=True)
        shutil.copytree(project, self.dir, ignore=COPY_IGNORE)
        for rel, code in (files or {}).items():
            (self.dir / rel).parent.mkdir(parents=True, exist_ok=True)
            (self.dir / rel).write_text(code)
        self.server, self.log = None, ""

    def start(self):
        self.stop()
        self.server = self.sandbox.start(["python3", "app.py"], self.dir)
        if self.server.wait_ready("/static/neuron.css"):
            return self.server.url
        self.stop()
        return None

    def stop(self):
        if self.server:
            self.log += self.server.stop()
            self.server = None

    def run_checks(self, checks):
        """Returns (passed, failure text)."""
        url = self.start()
        if not url:
            return False, "The app did not start:\n" + self.log[-1500:]
        try:
            for check in checks:
                ok, why = CheckRunner(url, restart=self.start).run(check)
                if not ok:
                    self.stop()
                    errors = "\n".join(l for l in self.log.splitlines()[-25:])
                    return False, f"Check '{check['name']}' failed: {why}" + (f"\nApp error output:\n{errors}" if "Traceback" in errors else "")
                url = self.server.url if self.server else self.start()
        finally:
            self.stop()
        return True, ""


def plan(request, client, meter):
    """Planner role: request -> validated spec (one repair round). Returns (spec, problems)."""
    messages = [{"role": "system", "content": prompts.PLANNER_SYSTEM},
                {"role": "user", "content": "Request: " + prompts.PLANNER_EXAMPLE_REQUEST},
                {"role": "assistant", "content": json.dumps(prompts.PLANNER_EXAMPLE_SPEC)},
                {"role": "user", "content": "Request: " + request}]
    problems = ["no reply"]
    for _ in range(2):
        reply = meter.chat(client, messages, max_tokens=1500, temperature=0.1, json_schema=SPEC_SCHEMA)
        try:
            raw = json.loads(reply.text[reply.text.index("{"): reply.text.rindex("}") + 1])
        except ValueError:
            raw, problems = None, ["the reply was not valid JSON"]
        if raw is not None:
            spec, problems = normalise(raw)
            if not problems:
                return spec, []
        messages += [{"role": "assistant", "content": reply.text},
                     {"role": "user", "content": "That specification cannot be used: " + "; ".join(problems) + ". Send a corrected one."}]
    return None, problems


def _builder_prompt(state, task):
    s = state.slice_for(task)
    parts = [prompts.KIT_GUIDE, "", "# Example of a similar file", "```python", prompts.EXAMPLES[task["example"]].rstrip(), "```"]
    if s["interfaces"]:
        parts += ["", "# Files that already exist in this project", s["interfaces"]]
    parts += ["", f"# Your task: {task['file']}", s["contract"]]
    if s.get("last_failure"):
        parts += ["", "# Your previous version failed", "```python", s["previous_code"].rstrip(), "```", s["last_failure"]]
        if s.get("advice"):
            parts += ["Reviewer's advice: " + s["advice"]]
        parts += ["Write a corrected complete file."]
    return "\n".join(parts)


def build_full(project, request, runner, sandbox, log=print, max_seconds=None):
    """Build (or resume building) a project. Returns a summary dict."""
    project, state, meter, t0 = Path(project), ProjectState(project), Meter(), time.time()
    out_of_time = lambda: max_seconds is not None and time.time() - t0 > max_seconds
    if state.exists():
        interrupted = state.resume()
        log(f"resuming: {sum(t['status'] == 'done' for t in state.tasks())} tasks already done, interrupted: {interrupted}")
    else:
        spec, problems = plan(request, runner.client("planner"), meter)
        if spec is None:
            return {"ok": False, "stage": "plan", "error": "; ".join(problems), "llm": vars(meter), "resumed": False}
        tasks, acceptance, purposes = expand(spec)
        prepare_project(project, spec["app_name"])
        state.create(request, "build", spec, tasks, acceptance, purposes)
        state.decide("plan", "spec", f"planned a {spec['kind']} called {spec['app_name']} with tasks: "
                     + ", ".join(t["id"] for t in tasks))
        log(f"planned {len(tasks)} tasks: {[t['id'] for t in tasks]}")
    state.journal("session", models={r: runner.model_for(r) for r in ("planner", "reviewer", "builder")})
    acceptance = state.acceptance()
    scratch = project.parent / (project.name + "__trial")
    while not out_of_time():
        task = state.next_task()
        if task is None:
            break
        state.update_task(task["id"], status="in_progress")
        checks = [c for c in acceptance if c["task"] == task["id"]]
        passed = False
        while len(task["attempts"]) < MAX_ATTEMPTS and not passed and not out_of_time():
            n = len(task["attempts"]) + 1
            attempt = {"n": n, "passed": False}
            reply = meter.chat(runner.client("builder"), [{"role": "system", "content": prompts.BUILDER_SYSTEM},
                                                          {"role": "user", "content": _builder_prompt(state, task)}],
                               max_tokens=1400, temperature=0.1 if n == 1 else 0.5)
            code = extract_code(reply.text)
            failure = None
            if code is None:
                failure = "The reply had no complete ```python block."
            else:
                attempt["code"] = code
                try:
                    compile(code, task["file"], "exec")
                    if f"def {task['must_define']}(" not in code:
                        failure = f"The file does not define {task['must_define']}(app)."
                except SyntaxError as e:
                    failure = f"The file is not valid Python: {e.msg} (line {e.lineno})."
            if failure is None:
                ok, failure = TrialRun(project, sandbox, scratch, {task["file"]: code}).run_checks(checks)
                state.record_test(task["id"], n, ok, "passed" if ok else failure.splitlines()[0], failure)
                if ok and task.get("review") and not any(a.get("review_used") for a in task["attempts"]):
                    verdict = _content_review(state, code, runner.client("reviewer"), meter)
                    attempt["review_used"] = True
                    if verdict:
                        ok, failure = False, "A reviewer compared the page with the request. Missing: " + "; ".join(verdict)
                        state.decide(task["id"], "review", failure)
                passed = ok
            if passed:
                (project / task["file"]).parent.mkdir(parents=True, exist_ok=True)
                (project / task["file"]).write_text(code)
                attempt["passed"] = True
            else:
                attempt["failure"] = failure
                if code is not None and len(task["attempts"]) + 1 < MAX_ATTEMPTS:
                    try:
                        advice = meter.chat(runner.client("reviewer"), [
                            {"role": "system", "content": prompts.REVIEWER_SYSTEM},
                            {"role": "user", "content": f"Contract:\n{task['contract']}\n\nThe file:\n```python\n{code}```\n\nWhat happened:\n{failure[-1500:]}"}],
                            max_tokens=200, temperature=0.2).text.strip()
                    except LLMUnavailable:
                        advice = ""
                    attempt["advice"] = advice
                    state.decide(task["id"], "diagnosis", advice)
            state.add_attempt(task["id"], attempt)
            task = state.task(task["id"])
            log(f"  task {task['id']} attempt {n}: {'passed' if passed else 'failed - ' + (failure or '').splitlines()[0][:120]}")
        if not passed and out_of_time() and len(task["attempts"]) < MAX_ATTEMPTS:
            state.update_task(task["id"], status="pending")
            break
        state.update_task(task["id"], status="done" if passed else "failed")
        state.refresh_map()
    shutil.rmtree(scratch, ignore_errors=True)
    tasks = state.tasks()
    final_ok, final_why = False, "not all tasks are done"
    if all(t["status"] == "done" for t in tasks):
        final_ok, final_why = TrialRun(project, sandbox, scratch).run_checks(acceptance)
        state.record_test("final", 1, final_ok, "all acceptance checks passed" if final_ok else final_why.splitlines()[0], final_why)
        shutil.rmtree(scratch, ignore_errors=True)
    return {"ok": final_ok, "stage": "done" if state.finished() else "out of time", "error": "" if final_ok else final_why,
            "tasks": {t["id"]: {"status": t["status"], "attempts": len(t["attempts"])} for t in tasks},
            "llm": vars(meter), "model_loads": runner.loads, "seconds": round(time.time() - t0, 1)}


def _content_review(state, code, client, meter):
    """Reviewer role: is anything the owner asked for missing from the page? Returns a list (empty = fine)."""
    request = state.spec()["request"]
    schema = {"type": "object", "required": ["ok", "missing"],
              "properties": {"ok": {"type": "boolean"}, "missing": {"type": "array", "maxItems": 5, "items": {"type": "string"}}}}
    try:
        reply = meter.chat(client, [{"role": "system", "content": prompts.CONTENT_REVIEW_SYSTEM},
                                    {"role": "user", "content": f"The owner asked:\n{request}\n\nThe page's code:\n```python\n{code}```"}],
                           max_tokens=200, temperature=0.1, json_schema=schema)
        data = json.loads(reply.text[reply.text.index("{"): reply.text.rindex("}") + 1])
    except (LLMUnavailable, ValueError):
        return []
    missing = [str(m) for m in data.get("missing") or [] if str(m).strip()]
    return [] if data.get("ok") else missing[:5]


def build_base(project, request, runner, sandbox, log=print, max_seconds=None):
    """Without A and B: one prompt for the whole app, 'does it start?' as the only feedback."""
    project, meter, t0 = Path(project), Meter(), time.time()
    shutil.rmtree(project, ignore_errors=True)       # nothing is kept between sessions
    prepare_project(project)
    examples = "\n".join(f"```python\n{prompts.EXAMPLES[k].rstrip()}\n```" for k in ("schema", "entity", "dashboard", "home"))
    base = f"{prompts.KIT_GUIDE}\n\n# Example files\n{examples}\n\n{prompts.BASE_TASK}{request}"
    messages = [{"role": "system", "content": prompts.BASE_SYSTEM}, {"role": "user", "content": base}]
    scratch = project.parent / (project.name + "__trial")
    rounds, ok, why = [], False, ""
    for n in range(1, MAX_ATTEMPTS + 1):
        if max_seconds is not None and time.time() - t0 > max_seconds:
            why = "out of time"
            break
        reply = meter.chat(runner.client("builder"), messages, max_tokens=3000, temperature=0.1 if n == 1 else 0.5)
        files = extract_files(reply.text)
        if "schema.py" not in files:
            why = "The reply did not contain schema.py as 'FILE: schema.py' followed by a python block."
        else:
            why = ""
            for rel, code in files.items():
                try:
                    compile(code, rel, "exec")
                except SyntaxError as e:
                    why = f"{rel} is not valid Python: {e.msg} (line {e.lineno})."
            if not why:
                ok, why = TrialRun(project, sandbox, scratch, files).run_checks(
                    [{"name": "home page opens", "steps": [{"get": "/", "expect_status": [200]}]}])
        rounds.append({"n": n, "files": sorted(files), "ok": ok, "problem": why.splitlines()[0] if why else ""})
        log(f"  round {n}: {'app starts' if ok else 'failed - ' + rounds[-1]['problem'][:120]}")
        if files and (ok or n == MAX_ATTEMPTS or "schema.py" in files):
            for rel, code in files.items():       # keep the latest version on disk either way
                (project / rel).parent.mkdir(parents=True, exist_ok=True)
                (project / rel).write_text(code)
        if ok:
            break
        messages = messages[:2] + [{"role": "assistant", "content": reply.text[:6000]},
                                   {"role": "user", "content": f"That did not work.\n{why[-1500:]}\nSend all the files again, corrected."}]
    shutil.rmtree(scratch, ignore_errors=True)
    return {"ok": ok, "stage": "done", "error": "" if ok else why, "rounds": rounds, "llm": vars(meter),
            "model_loads": runner.loads, "seconds": round(time.time() - t0, 1)}
